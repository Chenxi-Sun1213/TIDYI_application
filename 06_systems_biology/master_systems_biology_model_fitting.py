#!/usr/bin/env python3
"""Master entry point for Objective 6: systems biology model fitting.

Run using the prepared ASTRID abundance and TIDYI rate inputs:

    python master_systems_biology_model_fitting.py

Prepare fresh abundance and rates without running systems-biology fits:

    python prepare_systems_biology_inputs.py \
        --tidyi-source-root /path/containing/tidyi \
        --tidyi-version-label <version-or-commit> \
        --output-dir outputs/new_tidyi_inputs

Then pass ``outputs/new_tidyi_inputs/ty_df`` to ``--tidyi-input-root`` below.

Run with rate CSVs produced by a colleague's replacement TIDYI:

    python master_systems_biology_model_fitting.py \
        --tidyi-input-root /path/to/new/ty_df \
        --tidyi-version-label <version-or-commit> \
        --tidyi-model-label <model-name> \
        --tidyi-formula-label <formula-name>

The replacement directory must contain the same five filenames and the same
13-column TIDYI contract used by the legacy analysis.
Its parent directory must also contain the paired
``astrid_mouse_cell_abundance.csv`` and ``astrid_condition_cell_abundance.csv``
generated by the input producer.
Replacement rates must be recomputed on the same ASTRID cells, corrected labels
and pooled conditions. This master consumes those rates; it does not run TIDYI.
Model abundance is pooled from the ASTRID cell counts, independently of TIDYI.
Fit outputs are grouped under ``M4/`` and ``M23_refined/`` inside ``outputs/``.
The M2/M3 formula uses the original growth rate directly in both exponentials.

Inputs:
- ``outputs/input_preparation/ty_df`` (rates generated from ASTRID inputs).
- thesis Mukin/TMS AllRef_BM_0204 ASTRID directories.
- local support/tidyi_astrid_comparison_analysis.py, which contains the TMS prefix and Mukin
  RBC-contamination correction rules used for the abundance table.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys


RA_ROOT = Path(__file__).resolve().parents[1]
if str(RA_ROOT) not in sys.path:
    sys.path.insert(0, str(RA_ROOT))

from handover_utils import SourceReplacement, run_notebook_master  # noqa: E402


SOURCE_NOTEBOOK = Path(__file__).with_name("system_biology.ipynb")
OUTPUT_DIR = Path(__file__).parent / "outputs"
DEFAULT_TIDYI_INPUT_ROOT = Path(__file__).parent / "outputs/input_preparation/ty_df"
PIPELINE_HELPER = Path(__file__).parent / "support/tidyi_astrid_comparison_analysis.py"
MODEL_INPUT_HELPER = Path(__file__).parent / "support/system_biology_inputs.py"
MUKIN_ASTRID_ROOT = Path(
    "/scratch/chenxi.sun/thesis_project/mukin_qcdata/AllRef_BM_0204"
)
TMS_ASTRID_ROOT = Path(
    "/scratch/chenxi.sun/thesis_project/tms_qcdata/AllRef_BM_0204"
)

RATE_FILENAMES = (
    "mukin_young_spf_vs_old_spf_tidyi.csv",
    "mukin_young_spf_vs_young_gf_tidyi.csv",
    "mukin_old_spf_vs_old_gf_tidyi.csv",
    "tms_young_male_vs_young_female_tidyi.csv",
    "tms_old_male_vs_old_female_tidyi.csv",
)

SELECTED_CELLS = (2, 4, 6, 7, 9, 11, 12, 15, 18)

REFINED_CELLTYPE_SUFFIXES = (
    "b_pre",
    "dendritic",
    "monocyte_pro",
    "myeloid_progenitor",
    "myelomonocyte",
    "t_cd8",
)
REFINED_OUTPUT_DIR = OUTPUT_DIR / "M23_refined"
EXPECTED_OUTPUTS = (
    OUTPUT_DIR / "astrid_mouse_cell_abundance.csv",
    OUTPUT_DIR / "astrid_condition_cell_abundance.csv",
    OUTPUT_DIR / "abundance_variation_Marrow_Mukin.png",
    OUTPUT_DIR / "abundance_variation_Marrow_TMS.png",
    OUTPUT_DIR / "step1_scatter_Marrow_combined.png",
    OUTPUT_DIR / "M4/M4_grid_Marrow_combined_results.csv",
    *[
        OUTPUT_DIR / "M4" / f"M4_grid_Marrow_combined_{celltype}.png"
        for celltype in REFINED_CELLTYPE_SUFFIXES
    ],
    *[
        REFINED_OUTPUT_DIR / filename
        for filename in (
            "M23_refined_exponential_results.csv",
            "M23_refined_exponential_profiles.csv",
        )
    ],
    *[
        REFINED_OUTPUT_DIR / f"M23_{celltype}_{figure_kind}.png"
        for celltype in REFINED_CELLTYPE_SUFFIXES
        for figure_kind in ("fits", "parameter_grids", "profiles")
    ],
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kernel-name", default="python3")
    parser.add_argument(
        "--tidyi-input-root",
        type=Path,
        default=DEFAULT_TIDYI_INPUT_ROOT,
        help="Directory containing the five required pooled-condition TIDYI CSVs.",
    )
    parser.add_argument("--tidyi-version-label", default="prepared-rate-files")
    parser.add_argument("--tidyi-model-label", default="unspecified")
    parser.add_argument("--tidyi-formula-label", default="unspecified")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    tidyi_input_root = args.tidyi_input_root.expanduser().resolve()
    rate_inputs = tuple(tidyi_input_root / name for name in RATE_FILENAMES)
    replacements = {
        2: (
            SourceReplacement(
                'sys.path.insert(0, "/scratch/chenxi.sun/thesis_project/TIDYI/TIDYI_pattern/ty_pipeline_scripts")',
                "\n".join((
                    'sys.path.insert(0, "/scratch/chenxi.sun/thesis_project/TIDYI/TIDYI_pattern/ty_pipeline_scripts")',
                    f"sys.path.insert(0, {str(RA_ROOT / '03_death_proliferation/support')!r})",
                    f"sys.path.insert(0, {str(PIPELINE_HELPER.parent)!r})",
                )),
            ),
        ),
        4: (
            SourceReplacement(
                "/scratch/chenxi.sun/RA_project_handover/06_systems_biology/outputs/input_preparation/ty_df",
                str(tidyi_input_root),
            ),
        ),
        6: (
            SourceReplacement(
                "/scratch/chenxi.sun/RA_project_handover/06_systems_biology/outputs/astrid_mouse_cell_abundance.csv",
                str(OUTPUT_DIR / "astrid_mouse_cell_abundance.csv"),
            ),
        ),
        7: (
            SourceReplacement(
                "/scratch/chenxi.sun/RA_project_handover/06_systems_biology/outputs",
                str(OUTPUT_DIR),
                expected_count=1,
            ),
        ),
        **{
            cell: (
                SourceReplacement(
                    "/scratch/chenxi.sun/RA_project_handover/06_systems_biology/outputs/input_preparation/ty_df",
                    str(tidyi_input_root),
                ),
                SourceReplacement(
                    'output_root = Path("/scratch/chenxi.sun/RA_project_handover/06_systems_biology/outputs")',
                    f"output_root = Path({str(OUTPUT_DIR)!r})",
                ),
            )
            for cell in (15, 18)
        },
    }
    for cell in (2, 15, 18):
        replacements[cell] = (
            SourceReplacement(
                "/scratch/chenxi.sun/RA_project_handover/06_systems_biology/support",
                str(MODEL_INPUT_HELPER.parent),
            ),
            *replacements.get(cell, ()),
        )
    run_notebook_master(
        master_name="Objective 6 - systems biology model fitting",
        source_notebook=SOURCE_NOTEBOOK,
        cell_numbers=SELECTED_CELLS,
        expected_outputs=EXPECTED_OUTPUTS,
        authoritative_inputs=(
            *rate_inputs,
            tidyi_input_root.parent / "astrid_mouse_cell_abundance.csv",
            tidyi_input_root.parent / "astrid_condition_cell_abundance.csv",
            MUKIN_ASTRID_ROOT,
            MUKIN_ASTRID_ROOT / "BM_combined_ASTRID_results.csv",
            TMS_ASTRID_ROOT,
            PIPELINE_HELPER,
            MODEL_INPUT_HELPER,
        ),
        manifest_path=OUTPUT_DIR / "master_systems_biology_model_fitting_run_manifest.json",
        kernel_name=args.kernel_name,
        source_replacements=replacements,
        run_metadata={
            "tidyi_input_root": str(tidyi_input_root),
            "tidyi_version_label": args.tidyi_version_label,
            "tidyi_model_label": args.tidyi_model_label,
            "tidyi_formula_label": args.tidyi_formula_label,
            "required_tidyi_filenames": list(RATE_FILENAMES),
            "rate_annotation_source": "ASTRID comparison workflow with celltype_hb corrections",
            "abundance_unit": "dataset x mouse x tissue x cell_type",
            "model_abundance_source": "ASTRID condition-pooled cell counts",
            "model_rate_source": "selected TIDYI CSVs; recompute on the same ASTRID cells",
            "model_input_unit": "pooled condition x cell_type",
            "refined_models": ["M2", "M3"],
            "refined_formula": "kb * exp(b * gamma) / (ka * exp(a * gamma) - gamma)",
        },
    )


if __name__ == "__main__":
    main()
